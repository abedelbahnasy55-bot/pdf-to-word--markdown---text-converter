/**
 * Structural Cleaner & Running Headers Clustering (arabic-pdf-to-book v2.9.6)
 * Based on clean_md.py & clean_structure.py:
 * 1) Running Header/Footer Clustering: Finds recurring top/bottom patterns across pages and prunes them.
 * 2) Multi-Choice Option Exploder: Expands glued Egyptian textbook questions (-1 ... -2 ... or 1- ... 2- ...) into discrete lines.
 * 3) Fake Math Unwrapper: Unwraps false LaTeX $...$ or \text{...} into clean standard Arabic.
 * 4) Cross-page table row stabilizer.
 */

export class StructuralCleaner {
  /**
   * Explodes single-line questions with glued multiple choices into clean separated lines.
   * e.g. "ما حكم كذا؟ -1 جائز -2 مكروه -3 حرام" -> separated lines
   */
  public static explodeMultipleChoices(text: string): string {
    if (!text) return '';
    const lines = text.split('\n');
    const result: string[] = [];

    // Pattern matching Egyptian curriculum choices: -1 ... -2 or 1- ... 2- or (أ) ... (ب)
    const multiChoicePattern = /(?:^|(?<=[\s.،]))(?:-([٠-٩\d]{1,2})|([٠-٩\d]{1,2})-|\(([أ-يa-zA-Z\d٠-٩]{1,2})\))\s+/g;

    for (const rawLine of lines) {
      const line = rawLine.trim();
      const matches = [...line.matchAll(multiChoicePattern)];

      // If a line contains 2 or more choice markers, explode them!
      if (matches.length >= 2) {
        // Split while preserving markers
        let remaining = line;
        const explodedPieces: string[] = [];

        for (let i = matches.length - 1; i >= 0; i--) {
          const match = matches[i];
          const matchIndex = match.index || 0;
          const piece = remaining.slice(matchIndex).trim();
          remaining = remaining.slice(0, matchIndex).trim();
          explodedPieces.unshift(piece);
        }

        if (remaining) {
          result.push(remaining);
        }
        for (const p of explodedPieces) {
          if (p) result.push(`- ${p.replace(/^[-–—]\s*/, '')}`);
        }
      } else {
        result.push(rawLine);
      }
    }

    return result.join('\n');
  }

  /**
   * Cleans running headers and footers that repeat across page boundaries (---PAGE_BREAK---).
   */
  public static pruneRunningHeaders(markdown: string): string {
    if (!markdown || !markdown.includes('---PAGE_BREAK---')) {
      return markdown;
    }

    const pages = markdown.split(/---PAGE_BREAK---/);
    if (pages.length <= 2) return markdown;

    // Sample top 3 and bottom 3 lines of each page
    const topLinesCandidates: Record<string, number> = {};
    const bottomLinesCandidates: Record<string, number> = {};

    for (const page of pages) {
      const lines = page.trim().split('\n').map(l => l.trim()).filter(l => l.length > 0);
      if (lines.length >= 4) {
        // First 2 lines
        for (let i = 0; i < Math.min(2, lines.length); i++) {
          const norm = lines[i].replace(/[٠-٩\d\s\-_–—]/g, '');
          if (norm.length >= 6) {
            topLinesCandidates[norm] = (topLinesCandidates[norm] || 0) + 1;
          }
        }
        // Last 2 lines
        for (let i = Math.max(0, lines.length - 2); i < lines.length; i++) {
          const norm = lines[i].replace(/[٠-٩\d\s\-_–—]/g, '');
          if (norm.length >= 6) {
            bottomLinesCandidates[norm] = (bottomLinesCandidates[norm] || 0) + 1;
          }
        }
      }
    }

    // A candidate line that appears in >= 60% of pages is a running header/footer
    const threshold = Math.max(2, Math.floor(pages.length * 0.5));
    const runningHeaders = new Set<string>();

    for (const [key, count] of Object.entries(topLinesCandidates)) {
      if (count >= threshold) runningHeaders.add(key);
    }
    for (const [key, count] of Object.entries(bottomLinesCandidates)) {
      if (count >= threshold) runningHeaders.add(key);
    }

    if (runningHeaders.size === 0) return markdown;

    // Prune discovered running headers from pages
    const cleanedPages = pages.map(page => {
      const lines = page.split('\n');
      const filtered = lines.filter((line, idx) => {
        const norm = line.trim().replace(/[٠-٩\d\s\-_–—]/g, '');
        // Only strip if it's near top (first 3 lines) or near bottom (last 3 lines)
        const isNearEdge = idx < 3 || idx >= lines.length - 3;
        if (isNearEdge && runningHeaders.has(norm)) {
          return false;
        }
        return true;
      });
      return filtered.join('\n');
    });

    return cleanedPages.join('\n\n---PAGE_BREAK---\n\n');
  }

  /**
   * Unwraps fake math equations generated by OCR into standard Arabic text.
   * e.g. "$س = ٥$" or "\text{المسألة الأولى}"
   */
  public static unwrapFakeMath(text: string): string {
    if (!text) return '';
    return text
      .replace(/\\text\{([^\}]+)\}/g, '$1')
      .replace(/\\mathbf\{([^\}]+)\}/g, '$1')
      .replace(/\\mathrm\{([^\}]+)\}/g, '$1')
      .replace(/\\underline\{([^\}]+)\}/g, '<u>$1</u>')
      // Unwrap isolated dollar signs around Arabic text: e.g. $الفقه الشافعي$ -> الفقه الشافعي
      .replace(/\$([\u0600-\u06FF\s]+)\$/g, '$1');
  }

  /**
   * Full pipeline structural cleaner.
   */
  public static clean(markdown: string): string {
    let result = this.unwrapFakeMath(markdown);
    result = this.pruneRunningHeaders(result);
    result = this.explodeMultipleChoices(result);
    return result;
  }
}
